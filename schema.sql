CREATE TABLE IF NOT EXISTS billing_subscriptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealer_id INTEGER REFERENCES dealers(id) ON DELETE SET NULL,
    customer_name VARCHAR(120) NOT NULL,
    customer_email VARCHAR(254) NOT NULL,
    plan_code VARCHAR(20) NOT NULL,
    term_months INTEGER NOT NULL DEFAULT 1,
    monthly_net_amount NUMERIC(10, 2) NOT NULL,
    vat_rate NUMERIC(4, 2) NOT NULL DEFAULT 20,
    starts_at DATE,
    expires_at DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_billing_subscriptions_plan CHECK (plan_code IN ('starter', 'growth', 'enterprise')),
    CONSTRAINT ck_billing_subscriptions_amount_positive CHECK (monthly_net_amount > 0),
    CONSTRAINT ck_billing_subscriptions_term CHECK (term_months IN (1, 3, 6, 12))
);

CREATE INDEX IF NOT EXISTS ix_billing_subscriptions_customer_email ON billing_subscriptions(customer_email);
CREATE INDEX IF NOT EXISTS ix_billing_subscriptions_dealer_id ON billing_subscriptions(dealer_id);
CREATE INDEX IF NOT EXISTS ix_billing_subscriptions_expires_at ON billing_subscriptions(expires_at);

CREATE TABLE IF NOT EXISTS billing_payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id INTEGER NOT NULL REFERENCES billing_subscriptions(id) ON DELETE CASCADE,
    period_start DATE NOT NULL,
    due_date DATE NOT NULL,
    net_amount NUMERIC(10, 2) NOT NULL,
    vat_rate NUMERIC(4, 2) NOT NULL,
    vat_amount NUMERIC(10, 2) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    provider_order_id VARCHAR(64),
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_billing_payments_subscription_period UNIQUE (subscription_id, period_start),
    CONSTRAINT ck_billing_payments_status CHECK (status IN ('pending', 'paid', 'failed')),
    CONSTRAINT ck_billing_payments_amounts_nonnegative CHECK (
        net_amount >= 0 AND vat_amount >= 0 AND total_amount >= 0
    )
);

CREATE INDEX IF NOT EXISTS ix_billing_payments_subscription_id ON billing_payments(subscription_id);
CREATE INDEX IF NOT EXISTS ix_billing_payments_due_date ON billing_payments(due_date);
CREATE INDEX IF NOT EXISTS ix_billing_payments_created_at ON billing_payments(created_at);
CREATE UNIQUE INDEX IF NOT EXISTS ix_billing_payments_provider_order_id
    ON billing_payments(provider_order_id) WHERE provider_order_id IS NOT NULL;
