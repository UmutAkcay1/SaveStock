-- Reference PostgreSQL schema for SaveStock. Alembic migrations are the
-- deployment source of truth; this file is retained for manual inspection.

CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    barcode VARCHAR(80) UNIQUE,
    name VARCHAR(160) NOT NULL,
    unit VARCHAR(24) NOT NULL DEFAULT 'adet',
    category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_sku_not_blank CHECK (length(trim(sku)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_products_sku ON products(sku);
CREATE UNIQUE INDEX IF NOT EXISTS ix_products_barcode ON products(barcode);
CREATE INDEX IF NOT EXISTS ix_products_name ON products(name);

CREATE TABLE IF NOT EXISTS dealers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS batches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    dealer_id INTEGER NOT NULL REFERENCES dealers(id) ON DELETE RESTRICT,
    batch_code VARCHAR(80) NOT NULL,
    expiry_date DATE NOT NULL,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_batches_product_dealer_code UNIQUE (product_id, dealer_id, batch_code),
    CONSTRAINT ck_batches_quantity_nonnegative CHECK (quantity_on_hand >= 0)
);

CREATE INDEX IF NOT EXISTS ix_batches_product_id ON batches(product_id);
CREATE INDEX IF NOT EXISTS ix_batches_expiry_date ON batches(expiry_date);

CREATE TABLE IF NOT EXISTS stock_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id INTEGER NOT NULL REFERENCES batches(id) ON DELETE RESTRICT,
    movement_type VARCHAR(3) NOT NULL,
    quantity INTEGER NOT NULL,
    is_adjustment BOOLEAN NOT NULL DEFAULT FALSE,
    note VARCHAR(240),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_movements_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_movements_type CHECK (movement_type IN ('IN', 'OUT'))
);

CREATE INDEX IF NOT EXISTS ix_stock_movements_batch_id ON stock_movements(batch_id);
CREATE INDEX IF NOT EXISTS ix_stock_movements_created_at ON stock_movements(created_at);
CREATE INDEX IF NOT EXISTS ix_stock_movements_created_at_id ON stock_movements(created_at, id);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'user',
    dealer_id INTEGER REFERENCES dealers(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_role CHECK (role IN ('admin', 'user'))
);

CREATE INDEX IF NOT EXISTS ix_users_email ON users(email);

CREATE TABLE IF NOT EXISTS user_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    login_activity_recorded BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_user_sessions_user_id ON user_sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_user_sessions_expires_at ON user_sessions(expires_at);

CREATE TABLE IF NOT EXISTS auth_login_attempts (
    key_hash VARCHAR(64) PRIMARY KEY,
    window_started TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS ix_auth_login_attempts_window_started
    ON auth_login_attempts(window_started);

CREATE TABLE IF NOT EXISTS stock_idempotency_records (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    key VARCHAR(128) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    response_body JSON NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, key)
);

ALTER TABLE user_sessions
    ADD COLUMN IF NOT EXISTS login_activity_recorded BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS user_activities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    event_type VARCHAR(32) NOT NULL,
    description VARCHAR(240) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_activities_event_type CHECK (event_type IN (
        'LOGIN', 'LOGOUT', 'PROFILE_UPDATE', 'PASSWORD_CHANGE',
        'PRODUCT_CREATE', 'PRODUCT_UPDATE', 'CATEGORY_CREATE', 'USER_CREATE', 'USER_ACTIVATE',
        'USER_DEACTIVATE', 'DEALER_CREATE', 'STOCK_IN', 'STOCK_OUT', 'STOCK_ADJUSTMENT',
        'STOCK_REQUEST_CREATE', 'STOCK_REQUEST_FULFILL', 'STOCK_REQUEST_REJECT',
        'BILLING_SUBSCRIPTION_CREATE', 'BILLING_PAYMENT_PAID', 'BILLING_PERIOD_CREATE'
    ))
);

CREATE INDEX IF NOT EXISTS ix_user_activities_user_id ON user_activities(user_id);
CREATE INDEX IF NOT EXISTS ix_user_activities_created_at ON user_activities(created_at);
CREATE INDEX IF NOT EXISTS ix_user_activities_user_created_id
    ON user_activities(user_id, created_at, id);
CREATE INDEX IF NOT EXISTS ix_user_activities_created_id
    ON user_activities(created_at, id);

CREATE TABLE IF NOT EXISTS stock_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealer_id INTEGER NOT NULL REFERENCES dealers(id) ON DELETE RESTRICT,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    requested_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    requested_quantity INTEGER NOT NULL,
    fulfilled_quantity INTEGER NOT NULL DEFAULT 0,
    source_dealer_id INTEGER REFERENCES dealers(id) ON DELETE SET NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending',
    note VARCHAR(240),
    resolution_note VARCHAR(240),
    reviewed_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT ck_stock_requests_quantity_positive CHECK (requested_quantity > 0),
    CONSTRAINT ck_stock_requests_fulfilled_nonnegative CHECK (fulfilled_quantity >= 0),
    CONSTRAINT ck_stock_requests_status CHECK (
        status IN ('pending', 'partially_fulfilled', 'fulfilled', 'rejected')
    )
);

CREATE INDEX IF NOT EXISTS ix_stock_requests_dealer_id ON stock_requests(dealer_id);
CREATE INDEX IF NOT EXISTS ix_stock_requests_product_id ON stock_requests(product_id);
CREATE INDEX IF NOT EXISTS ix_stock_requests_requested_by_user_id ON stock_requests(requested_by_user_id);
CREATE INDEX IF NOT EXISTS ix_stock_requests_status ON stock_requests(status);
CREATE INDEX IF NOT EXISTS ix_stock_requests_created_at ON stock_requests(created_at);
CREATE INDEX IF NOT EXISTS ix_stock_requests_dealer_created_id
    ON stock_requests(dealer_id, created_at, id);

